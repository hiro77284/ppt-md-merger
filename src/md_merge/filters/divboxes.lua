-- % :::

-- % ::: {.note}
-- % ここは補足説明です。本文より少し目立たせるが、警告ほど強くはしない。
-- % :::

-- % ::: {.warning}
-- % ここは注意書きです。読み飛ばされると困る内容を置く。
-- % :::

-- % leadlinebox
-- % 枠なし、やや大きめ、ゴシック太字。擬似見出し用。

-- % notebox
-- % 薄い囲み。補足情報向け。

-- % warningbox
-- % 少し強い囲み。注意喚起向け。
-- % =======================

-- BLOCK_ENV: fenced div クラス → tcolorbox 環境名。semantics.yaml の blocks のうち
-- latex.box: true のクラスから tools/gen_lua_semantics.py が生成する。手で編集せず
-- semantics.yaml を直して `python tools/gen_lua_semantics.py` で再生成すること。
-- 属性→tcolorbox オプション変換（build_options / allowed / ordered_keys）はこの表とは
-- 別に手維持する（単純表ではないため生成対象外）。
-- >>> GENERATED by tools/gen_lua_semantics.py from semantics.yaml — DO NOT EDIT
local BLOCK_ENV = {
  note = "notebox",
  warning = "warningbox",
  leadline = "leadlinebox",
  widequote = "widequotebox",
}
-- <<< GENERATED

-- ── engine: typst ─────────────────────────────────────────────────────────
-- 同じクラスを #sem-box("kind", 属性...)[中身] に変換する（関数と既定の見た目は
-- templates/semantic_macros.typ）。属性は LaTeX 版と同じ名前を受け付け、Typst の値に
-- 読み替える。読み替えられない値は警告して無視する（Typst への生の注入を防ぐ）。

local TYPST_SIZE = {  -- LaTeX のサイズ命令 → 本文に対する倍率
  ["\\tiny"] = "0.5em", ["\\scriptsize"] = "0.7em", ["\\footnotesize"] = "0.8em",
  ["\\small"] = "0.9em", ["\\normalsize"] = "1em", ["\\large"] = "1.2em",
  ["\\Large"] = "1.44em", ["\\LARGE"] = "1.73em", ["\\huge"] = "2.07em", ["\\Huge"] = "2.49em",
}

local XCOLOR = {  -- xcolor の基本色名 → RGB（Typst の同名色とは値が違うので明示する）
  black = "#000000", white = "#ffffff", red = "#ff0000", green = "#00ff00", blue = "#0000ff",
  cyan = "#00ffff", magenta = "#ff00ff", yellow = "#ffff00", gray = "#808080",
  lightgray = "#bfbfbf", darkgray = "#404040", orange = "#ff8000", brown = "#bf8040",
  purple = "#bf0040", violet = "#800080", teal = "#008080", olive = "#808000",
  lime = "#bfff00", pink = "#ffbfbf",
}

local function typst_warn(msg)
  io.stderr:write("[divboxes] " .. msg .. "\n")
end

local function typst_trim(s)
  return (s:gsub("^%s+", ""):gsub("%s+$", ""))
end

-- 長さ: 0.7\linewidth 等は % に、%/mm/cm/pt/em/in はそのまま。
local function typst_length(v)
  v = typst_trim(v)
  local n = v:match("^([%d.]+)\\[a-z]*width$") or v:match("^([%d.]+)\\hsize$")
  if n then
    return string.format("%g%%", tonumber(n) * 100)
  end
  if v:match("^[%d.]+%%$") or v:match("^[%d.]+mm$") or v:match("^[%d.]+cm$")
      or v:match("^[%d.]+pt$") or v:match("^[%d.]+em$") or v:match("^[%d.]+in$") then
    return v
  end
  local bp = v:match("^([%d.]+)bp$")
  if bp then return bp .. "pt" end
  return nil
end

-- 色: xcolor の name / name!pct / name!pct!name2 と #RRGGBB。
local function typst_color(v)
  v = typst_trim(v)
  if v:match("^#%x%x%x%x%x%x$") then
    return 'rgb("' .. v .. '")'
  end
  local parts = {}
  for p in v:gmatch("[^!]+") do parts[#parts + 1] = p end
  local c1 = XCOLOR[parts[1] or ""]
  if not c1 then return nil end
  if #parts == 1 then return 'rgb("' .. c1 .. '")' end
  local pct = tonumber(parts[2])
  local c2 = XCOLOR[parts[3] or "white"]
  if not pct or not c2 or #parts > 3 then return nil end
  return string.format('color.mix((rgb("%s"), %g%%), (rgb("%s"), %g%%))', c1, pct, c2, 100 - pct)
end

local function typst_bool(v)
  v = typst_trim(v:lower())
  if v == "true" or v == "yes" or v == "1" then return "true" end
  if v == "false" or v == "no" or v == "0" then return "false" end
  return nil
end

-- 属性名 → (Typst の引数名, 変換関数)
local TYPST_ARGS = {
  { "frame", "frame", typst_bool },
  { "width", "width", typst_length },
  { "center", "center", typst_bool },
  { "colback", "fill", typst_color },
  { "colframe", "stroke-color", typst_color },
  { "boxrule", "rule", typst_length },
  { "left", "left", typst_length },
  { "right", "right", typst_length },
  { "top", "top", typst_length },
  { "bottom", "bottom", typst_length },
  { "before_skip", "above", typst_length },
  { "after_skip", "below", typst_length },
  { "fontsize", "size", function(v) return TYPST_SIZE[typst_trim(v)] or typst_length(v) end },
  { "stretch", "stretch", function(v) v = typst_trim(v); return v:match("^[%d.]+$") and v or nil end },
}

local function typst_box(el, kind)
  local args = { '"' .. kind .. '"' }
  for _, spec in ipairs(TYPST_ARGS) do
    local attr, name, conv = spec[1], spec[2], spec[3]
    local v = el.attributes[attr]
    if v and v ~= "" then
      local tv = conv(v)
      if tv then
        args[#args + 1] = name .. ": " .. tv
      else
        typst_warn("." .. kind .. " の " .. attr .. "=" .. v .. " は Typst に読み替えられないので無視します")
      end
    end
  end
  local out = { pandoc.RawBlock("typst", "#sem-box(" .. table.concat(args, ", ") .. ")[") }
  for _, b in ipairs(el.content) do out[#out + 1] = b end
  out[#out + 1] = pandoc.RawBlock("typst", "]")
  return out
end

function Div(el)
    if FORMAT == "typst" then
        for _, c in ipairs(el.classes) do
            if BLOCK_ENV[c] then return typst_box(el, c) end
        end
        return nil
    end

    local allowed = {
        left = true,
        right = true,
        top = true,
        bottom = true,
        colback = true,
        colframe = true,
        boxrule = true,
        fontsize = true,
        before_skip = true,
        after_skip = true,
        frame = true,
        stretch = true,
        width = true,
        center = true
        -- style は危険なので外す
    }

    local function trim(s)
        return (s:gsub("^%s+", ""):gsub("%s+$", ""))
    end

    local function oneline(s)
        s = s:gsub("[\r\n]+", " ")
        s = s:gsub("%s%s+", " ")
        return trim(s)
    end

    local function latex_value(s)
        -- 最低限の整形だけする
        return oneline(s)
    end

    local function bool_value(s)
        s = trim(s:lower())
        if s == "true" or s == "yes" or s == "1" then
            return true
        elseif s == "false" or s == "no" or s == "0" then
            return false
        end
        return nil
    end

    local function font_key_for(kind)
        -- 各 box は "kind/font" スタイルキーを持つ（tcolorbox 定義側と一致）。
        if BLOCK_ENV[kind] then
            return kind .. "/font"
        end
        return nil
    end

    local function build_options(attrs, kind)
        local opts = {}     -- オプションリストを初期化
        local base_style = kind .. "/noframe"  -- 文字列を連結してデフォルトのスタイルを設定

        -- 順序固定で処理
        local ordered_keys = {
            "frame",
            "fontsize",
            "stretch",
            "before_skip",
            "after_skip",
            "left",
            "right",
            "top",
            "bottom",
            "colback",
            "colframe",
            "boxrule",
            "width",
            "center"
        }

        for _, k in ipairs(ordered_keys) do
            local v = attrs[k]
            if v and allowed[k] then
                v = latex_value(v)

                if k == "fontsize" then
                    local fontkey = font_key_for(kind)
                    if fontkey and v ~= "" then
                        table.insert(opts, fontkey .. "={" .. v .. "}")
                    end

                elseif k == "stretch" then
                    if v ~= "" then
                        table.insert(opts, kind .. "/stretch={" .. v .. "}")
                    end

                elseif k == "before_skip" then
                    if v ~= "" then
                        table.insert(opts, "before skip={" .. v .. "}")
                    end

                elseif k == "after_skip" then
                    if v ~= "" then
                        table.insert(opts, "after skip={" .. v .. "}")
                    end

                elseif k == "frame" then
                    local b = bool_value(v)
                    if b == true then
                        base_style = kind .. "/frame"
                    elseif b == false then
                        base_style = kind .. "/noframe"
                    end

                elseif k == "center" then
                    local b = bool_value(v)
                    if b == true then
                        table.insert(opts, "center")
                    end

                else
                    if v ~= "" then
                        table.insert(opts, k .. "={" .. v .. "}")
                    end
                end
            end
        end

        table.insert(opts, 1, base_style)
        return table.concat(opts, ",")      -- カンマ区切りのオプション文字列を返す
    end

    local function wrap_env(envname, div, kind)
        local blocks = {}
        local optstr = build_options(div.attributes, kind)

        if optstr ~= "" then
            table.insert(blocks, pandoc.RawBlock(
                "latex",
                "\\begin{" .. envname .. "}[" .. optstr .. "]"
            ))
        else
            table.insert(blocks, pandoc.RawBlock(
                "latex",
                "\\begin{" .. envname .. "}"
            ))
        end

        for _, b in ipairs(div.content) do
            table.insert(blocks, b)
        end

        table.insert(blocks, pandoc.RawBlock(
            "latex",
            "\\end{" .. envname .. "}"
        ))

        return blocks
    end

    -- div に付いた最初の box クラスを env にマップ（kind=クラス名）。
    for _, c in ipairs(el.classes) do
        local env = BLOCK_ENV[c]
        if env then
            return wrap_env(env, el, c)
        end
    end
end
