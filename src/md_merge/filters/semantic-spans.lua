-- filters/semantic-spans.lua
-- インライン bracketed span [text]{.class} を出力形式ごとに lower する。
--   LaTeX: \macro{...}（マクロは defaults/pandoc/semantic_macros.tex で定義）
--   Typst: #func[...]（関数は templates/semantic_macros.typ で定義）
--   HTML : .kbd -> <kbd>, .path -> <code>。それ以外は素の <span class>（CSS が装飾）
--   その他の形式: 素通り（span をそのまま）
--
-- 下の GENERATED ブロック（LATEX_MACRO=class→LaTeX マクロ名、TYPST_FUNC=class→Typst 関数名、
-- HTML_TAG=class→HTML 要素）は
-- src/md_merge/semantics.yaml の inlines から tools/gen_lua_semantics.py が生成する。
-- 手で編集せず semantics.yaml を直して `python tools/gen_lua_semantics.py` で再生成すること。
-- マクロは semantic_macros.tex 側と一致（sem 接頭辞で名前空間化。emph のみ LaTeX ネイティブ）。
-- HTML_TAG に無いクラスは素の <span class> のまま CSS(semantic.css) に委ねる。

-- >>> GENERATED by tools/gen_lua_semantics.py from semantics.yaml — DO NOT EDIT
local LATEX_MACRO = {
  term = "semterm",
  keyword = "semkeyword",
  path = "sempath",
  kbd = "semkbd",
  emph = "emph",
  rightlabel = "semrightlabel",
}
local TYPST_FUNC = {
  term = "semterm",
  keyword = "semkeyword",
  path = "sempath",
  kbd = "semkbd",
  emph = "emph",
  rightlabel = "semrightlabel",
}
local HTML_TAG = {
  path = "code",
  kbd = "kbd",
}
-- <<< GENERATED

local function first_known_class(el, tbl)
  for _, c in ipairs(el.classes) do
    if tbl[c] then return c end
  end
  return nil
end

function Span(el)
  if FORMAT:match("latex") then
    local c = first_known_class(el, LATEX_MACRO)
    if not c then return nil end
    local out = pandoc.List({})
    out:insert(pandoc.RawInline("latex", "\\" .. LATEX_MACRO[c] .. "{"))
    out:extend(el.content)
    out:insert(pandoc.RawInline("latex", "}"))
    return out
  elseif FORMAT == "typst" then
    local c = first_known_class(el, TYPST_FUNC)
    if not c then return nil end
    local out = pandoc.List({})
    out:insert(pandoc.RawInline("typst", "#" .. TYPST_FUNC[c] .. "["))
    out:extend(el.content)
    -- 末尾の ; は直後の "." や "(" を式の続き（メソッド呼び出し等）と解釈させないため
    out:insert(pandoc.RawInline("typst", "];"))
    return out
  elseif FORMAT:match("html") then
    local c = first_known_class(el, HTML_TAG)
    if not c then return nil end  -- 他クラスは素の <span class>（CSS で装飾）
    local tag = HTML_TAG[c]
    local cls = table.concat(el.classes, " ")
    local out = pandoc.List({})
    out:insert(pandoc.RawInline("html", "<" .. tag .. ' class="' .. cls .. '">'))
    out:extend(el.content)
    out:insert(pandoc.RawInline("html", "</" .. tag .. ">"))
    return out
  end
  return nil
end
