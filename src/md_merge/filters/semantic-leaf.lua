-- filters/semantic-leaf.lua
-- リーフ記法 {{vspace:N}} / {{pagebreak}} / {{vfill}} を出力形式ごとに lower する。
-- これらは markdown 上では素のテキスト（独立段落）なので、段落全体がマーカー 1 個
-- だけのときにブロックごと置換する。
--   LaTeX: \par\vspace{N\baselineskip} / \newpage / \vspace*{\fill}
--   Typst: #v(N * 1.65em) / #pagebreak(weak: true) / #v(1fr)
--   HTML : <div class="vspace|pagebreak|vfill">（CSS が装飾。vspace は高さを指定）
--   その他の形式: 素通り
-- vspace の引数は数値（既定単位の倍。LaTeX=\baselineskip / HTML=em）または単位付き
-- 長さ（{{vspace:5mm}} / {{vspace:1.5cm}} 等）。単位付きはその長さをそのまま使う。
--
-- 下の GENERATED ブロック（LEAF_LATEX / LEAF_TYPST とその _UNIT、LEAF_HTML）は semantics.yaml の
-- leaves から tools/gen_lua_semantics.py が生成する。手で編集せず semantics.yaml を直して
-- 再生成すること。テンプレート内の %{arg} はリーフ引数（未指定時 "1"）で置換する。
-- unit が定義されたリーフ×形式は、%{arg} が純数値のとき末尾に unit を付す。

-- >>> GENERATED by tools/gen_lua_semantics.py from semantics.yaml — DO NOT EDIT
local LEAF_LATEX = {
  vspace = "\\par\\vspace{%{arg}}",
  pagebreak = "\\newpage",
  vfill = "\\vspace*{\\fill}",
}
local LEAF_LATEX_UNIT = {
  vspace = "\\baselineskip",
}
local LEAF_TYPST = {
  vspace = "#v(%{arg})",
  pagebreak = "#pagebreak(weak: true)",
  vfill = "#v(1fr)",
}
local LEAF_TYPST_UNIT = {
  vspace = " * 1.65em",
}
local LEAF_HTML = {
  vspace = { tag = "div", class = "vspace", style = "height:%{arg}", unit = "em" },
  pagebreak = { tag = "div", class = "pagebreak" },
  vfill = { tag = "div", class = "vfill" },
}
-- <<< GENERATED

local KNOWN = {}
for k in pairs(LEAF_LATEX) do KNOWN[k] = true end
for k in pairs(LEAF_TYPST) do KNOWN[k] = true end
for k in pairs(LEAF_HTML) do KNOWN[k] = true end

local function is_html()
  return FORMAT:match("html") or FORMAT:match("revealjs")
end

-- 引数を解決する。未指定は "1"。unit が与えられ、かつ arg が純数値（12 / .5 / 1.5）なら
-- 末尾に unit を付す（既定単位の倍）。単位付き（5mm 等）はそのまま返す。
local function resolve_arg(arg, unit)
  local a = (arg ~= "" and arg or "1")
  if unit and unit ~= "" and a:match("^[%d.]+$") then
    return a .. unit
  end
  return a
end

-- テンプレート中の %{arg} を解決済み引数で置換。
local function subst(tmpl, arg, unit)
  return (tmpl:gsub("%%{arg}", resolve_arg(arg, unit)))
end

local function latex_for(name, arg)
  local tmpl = LEAF_LATEX[name]
  if not tmpl then return nil end
  return subst(tmpl, arg, LEAF_LATEX_UNIT[name])
end

local function typst_for(name, arg)
  local tmpl = LEAF_TYPST[name]
  if not tmpl then return nil end
  return subst(tmpl, arg, LEAF_TYPST_UNIT[name])
end

local function html_for(name, arg)
  local spec = LEAF_HTML[name]
  if not spec then return nil end
  local attrs = ' class="' .. spec.class .. '"'
  if spec.style then
    attrs = attrs .. ' style="' .. subst(spec.style, arg, spec.unit) .. '"'
  end
  return "<" .. spec.tag .. attrs .. "></" .. spec.tag .. ">"
end

local function handle_leaf(el)
  -- マーカーは素の文字列 1 個の段落だけ。stringify はインラインコードの中身も拾うので、
  -- 表のセルに `{{pagebreak}}` と書いた用例まで lower してしまう（Plain なので）。
  if #el.content ~= 1 or el.content[1].t ~= "Str" then
    return nil
  end
  local s = el.content[1].text
  -- arg は数値（{{vspace:0.5}} / {{vspace:2}}）または単位付き長さ（{{vspace:5mm}} /
  -- {{vspace:1.5cm}}）。数値部 [%d.]* に続けて任意の単位 %a*（mm/cm/pt/em/ex/in/bp/pc 等）。
  local name, arg = s:match("^{{(%a+):?([%d.]*%a*)}}$")
  if not name or not KNOWN[name] then
    return nil
  end
  if FORMAT:match("latex") then
    local tex = latex_for(name, arg)
    if tex then return pandoc.RawBlock("latex", tex) end
  elseif FORMAT == "typst" then
    local typ = typst_for(name, arg)
    if typ then return pandoc.RawBlock("typst", typ) end
  elseif is_html() then
    local html = html_for(name, arg)
    if html then return pandoc.RawBlock("html", html) end
  end
  return nil  -- 他形式: マーカーは素通り
end

function Para(el)
  return handle_leaf(el)
end

function Plain(el)
  return handle_leaf(el)
end
