"""Content fingerprints for insertmd drift detection.

A fingerprint captures, per markdown file referenced by ``procedure.insertmd``:

* ``tokens``    — normalized token count (ASCII words + individual CJK/symbol chars)
* ``headings``  — ordered list of markdown heading texts (code fences ignored)
* ``idmarkers`` — number of ``{{#id:...}}`` markers
* ``sha8``      — 8-hex SHA-256 prefix of the normalized text (exact-match fast path)
* ``simhash``   — 64-bit SimHash (hex) of the token bag (fuzzy similarity)

Check data is generated by the ``checkgen`` command into a separate YAML file and
verified during ``merge``. A warning is raised when content drifts significantly:
headings changed (immediate), token count beyond ±20%, or SimHash Hamming distance
above the threshold. An exact ``sha8`` match short-circuits with no warning.
"""

from __future__ import annotations

import hashlib
import re
from collections import Counter
from pathlib import Path

import yaml

_ID_RE = re.compile(r"\{\{#id:[^:}]+:[^:}]+:[^}]+\}\}")
_HEADING_RE = re.compile(r"^\s{0,3}(#{1,6})\s+(.*?)\s*#*\s*$")
_FENCE_RE = re.compile(r"^\s*(```|~~~)")
_WS_RE = re.compile(r"\s+")
# ASCII alphanumeric runs as one token; every other non-space char (incl. each
# CJK character and punctuation) as its own token — language-agnostic counting.
_TOKEN_RE = re.compile(r"[A-Za-z0-9]+|[^\sA-Za-z0-9]")

# Warning thresholds.
TOKEN_TOLERANCE = 0.20
SIMHASH_HAMMING_THRESHOLD = 6


def _normalize(text: str) -> str:
    return _WS_RE.sub(" ", text).strip()


def tokenize(text: str) -> list[str]:
    return _TOKEN_RE.findall(_normalize(text))


def extract_headings(text: str) -> list[str]:
    headings: list[str] = []
    in_fence = False
    for line in text.splitlines():
        if _FENCE_RE.match(line):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        m = _HEADING_RE.match(line)
        if m:
            headings.append(m.group(2).strip())
    return headings


def count_id_markers(text: str) -> int:
    return len(_ID_RE.findall(text))


def sha8(text: str) -> str:
    return hashlib.sha256(_normalize(text).encode("utf-8")).hexdigest()[:8]


def _token_hash64(token: str) -> int:
    return int.from_bytes(hashlib.blake2b(token.encode("utf-8"), digest_size=8).digest(), "big")


def simhash64(tokens: list[str]) -> int:
    """64-bit SimHash (Charikar) over the weighted token bag. Deterministic."""
    if not tokens:
        return 0
    vec = [0] * 64
    for token, weight in Counter(tokens).items():
        h = _token_hash64(token)
        for i in range(64):
            if (h >> i) & 1:
                vec[i] += weight
            else:
                vec[i] -= weight
    out = 0
    for i in range(64):
        if vec[i] > 0:
            out |= 1 << i
    return out


def hamming64(a: int, b: int) -> int:
    return bin((a ^ b) & ((1 << 64) - 1)).count("1")


def fingerprint(text: str) -> dict:
    tokens = tokenize(text)
    return {
        "tokens": len(tokens),
        "headings": extract_headings(text),
        "idmarkers": count_id_markers(text),
        "sha8": sha8(text),
        "simhash": f"{simhash64(tokens):016x}",
    }


def compare(expected: dict, current: dict) -> list[str]:
    """Return human-readable reasons why *current* differs *significantly* from
    *expected*. Empty list = within tolerance (no warning).
    """
    if expected.get("sha8") and expected.get("sha8") == current.get("sha8"):
        return []  # identical content — fast path

    reasons: list[str] = []

    exp_h = list(expected.get("headings") or [])
    cur_h = list(current.get("headings") or [])
    if exp_h != cur_h:
        reasons.append(f"見出しが変化: {exp_h} → {cur_h}")

    exp_t = int(expected.get("tokens") or 0)
    cur_t = int(current.get("tokens") or 0)
    denom = exp_t if exp_t > 0 else 1
    if abs(cur_t - exp_t) / denom > TOKEN_TOLERANCE:
        pct = (cur_t - exp_t) / denom * 100
        reasons.append(
            f"トークン数が±{int(TOKEN_TOLERANCE * 100)}%超変化: {exp_t} → {cur_t} ({pct:+.0f}%)"
        )

    try:
        exp_s = int(str(expected.get("simhash") or "0"), 16)
        cur_s = int(str(current.get("simhash") or "0"), 16)
        dist = hamming64(exp_s, cur_s)
        if dist > SIMHASH_HAMMING_THRESHOLD:
            reasons.append(f"SimHash 距離が大きい: {dist}/64 (>{SIMHASH_HAMMING_THRESHOLD})")
    except ValueError:
        pass

    return reasons


def load_check_map(check_path: Path) -> dict[str, dict]:
    """Load a check YAML file into ``{mdfilename: fingerprint}`` (insertmd)."""
    with check_path.open(encoding="utf-8") as f:
        data = yaml.safe_load(f) or {}
    result: dict[str, dict] = {}
    for entry in data.get("entries") or []:
        name = entry.get("mdfilename")
        if name:
            result[name] = entry
    return result


# ── insertpptx fingerprints (slide count + ordered slide titles) ────────────


def read_slide_titles(pptx_path: Path) -> list[str]:
    """Return the ordered slide title-placeholder texts of a pptx (\"\" when absent)."""
    from pptx import Presentation  # lazy import — only needed for pptx checks

    prs = Presentation(str(pptx_path))
    titles: list[str] = []
    for slide in prs.slides:
        title = slide.shapes.title
        titles.append((title.text or "") if title is not None else "")
    return titles


def pptx_fingerprint(slide_titles: list[str]) -> dict:
    return {"slidecount": len(slide_titles), "titles": list(slide_titles)}


def compare_pptx(expected: dict, current: dict) -> list[str]:
    """Return reasons why the pptx structure drifted. Empty list = unchanged."""
    reasons: list[str] = []

    exp_c = int(expected.get("slidecount", -1))
    cur_c = int(current.get("slidecount", -1))
    if exp_c != cur_c:
        reasons.append(f"スライド数が変化: {exp_c} → {cur_c}")

    exp_t = list(expected.get("titles") or [])
    cur_t = list(current.get("titles") or [])
    if exp_t != cur_t:
        i = next(
            (k for k in range(max(len(exp_t), len(cur_t)))
             if (exp_t[k] if k < len(exp_t) else None) != (cur_t[k] if k < len(cur_t) else None)),
            None,
        )
        if i is not None:
            e = exp_t[i] if i < len(exp_t) else "(なし)"
            c = cur_t[i] if i < len(cur_t) else "(なし)"
            reasons.append(f"スライドタイトルが変化（{i + 1}枚目: {e!r} → {c!r} ほか）")
        else:
            reasons.append("スライドタイトルが変化")
    return reasons


def load_pptx_check_map(check_path: Path) -> dict[str, dict]:
    """Load a check YAML file into ``{pptxfilename: fingerprint}`` (insertpptx)."""
    with check_path.open(encoding="utf-8") as f:
        data = yaml.safe_load(f) or {}
    result: dict[str, dict] = {}
    for entry in data.get("pptx_entries") or []:
        name = entry.get("pptxfilename")
        if name:
            result[name] = entry
    return result


def verify_pptx_against_check(
    check_map: dict[str, dict], io_entries: list[tuple[str, Path]]
) -> list[tuple[str, list[str]]]:
    """Compare each (pptxfilename, resolved_path) against the stamped pptx fingerprint."""
    problems: list[tuple[str, list[str]]] = []
    for fname, path in io_entries:
        expected = check_map.get(fname)
        if expected is None:
            continue
        if not path.exists():
            problems.append((fname, ["ファイルが見つかりません（チェックデータには存在）"]))
            continue
        try:
            titles = read_slide_titles(path)
        except Exception as e:  # noqa: BLE001 - surface unreadable pptx as a finding
            problems.append((fname, [f"PPTX を読めません: {e}"]))
            continue
        reasons = compare_pptx(expected, pptx_fingerprint(titles))
        if reasons:
            problems.append((fname, reasons))
    return problems


def verify_against_check(
    check_map: dict[str, dict], io_entries: list[tuple[str, Path]]
) -> list[tuple[str, list[str]]]:
    """Compare each (mdfilename, resolved_path) against the stamped fingerprint.

    Returns ``[(mdfilename, reasons)]`` for entries that drifted significantly or
    are missing. Entries absent from *check_map* (added after stamping) are skipped.
    """
    problems: list[tuple[str, list[str]]] = []
    for fname, path in io_entries:
        expected = check_map.get(fname)
        if expected is None:
            continue
        if not path.exists():
            problems.append((fname, ["ファイルが見つかりません（チェックデータには存在）"]))
            continue
        text = path.read_text(encoding="utf-8-sig")
        reasons = compare(expected, fingerprint(text))
        if reasons:
            problems.append((fname, reasons))
    return problems
