#!/usr/bin/env python3
"""Code-generate the Lua filters' lookup tables from ``semantics.yaml``.

``semantics.yaml`` is the single source of truth for the semantic registry.
The pandoc (Lua) path cannot read YAML, so the inline/leaf lookup tables that
``semantic-spans.lua`` and ``semantic-leaf.lua`` consume are generated from the
registry into a ``-- >>> GENERATED ... -- <<< GENERATED`` region in each filter.

Usage::

    python tools/gen_lua_semantics.py            # rewrite the GENERATED regions
    python tools/gen_lua_semantics.py --check     # exit 1 if any region is stale

Run (without --check) after editing ``semantics.yaml`` and commit both files.
``--check`` is a drift guard suitable for CI / pre-commit.

Note: only ``inlines`` and ``leaves`` are generated. ``blocks`` env mappings live
in the box filters (divboxes.lua etc.) whose attribute handling is not a plain
table; those remain hand-maintained.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_ROOT / "src"))

from md_merge._semantics import load_semantics  # noqa: E402

_FILTERS_DIR = _ROOT / "src" / "md_merge" / "filters"

_BEGIN = "-- >>> GENERATED by tools/gen_lua_semantics.py from semantics.yaml — DO NOT EDIT"
_END = "-- <<< GENERATED"
_REGION_RE = re.compile(r"-- >>> GENERATED.*?-- <<< GENERATED[^\n]*", re.DOTALL)


_IDENT_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def _lua_str(s: str) -> str:
    """Render a Python string as a Lua double-quoted string literal."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _lua_key(name: str) -> str:
    """Render a table key: bare identifier if valid, else bracketed string."""
    return name if _IDENT_RE.match(name) else f"[{_lua_str(name)}]"


def _spans_body(sem) -> list[str]:
    lines = ["local LATEX_MACRO = {"]
    for name, rule in sem.inlines.items():
        macro = (rule.get("latex") or {}).get("macro")
        if macro:
            lines.append(f"  {name} = {_lua_str(str(macro))},")
    lines.append("}")
    lines.append("local TYPST_FUNC = {")
    for name, rule in sem.inlines.items():
        func = (rule.get("typst") or {}).get("func")
        if func:
            lines.append(f"  {name} = {_lua_str(str(func))},")
    lines.append("}")
    lines.append("local HTML_TAG = {")
    for name, rule in sem.inlines.items():
        tag = (rule.get("html") or {}).get("tag")
        if tag:
            lines.append(f"  {name} = {_lua_str(str(tag))},")
    lines.append("}")
    return lines


def _leaf_tmpl(rule, fmt: str):
    """Return (template, default_unit) for a leaf's rule in *fmt* (``latex`` / ``typst``).

    The rule is either a plain template string (no unit) or a mapping
    ``{tmpl, unit}`` where ``unit`` is appended to a bare-number ``%{arg}``.
    """
    spec = rule.get(fmt)
    if isinstance(spec, str):
        return spec, None
    if isinstance(spec, dict) and isinstance(spec.get("tmpl"), str):
        return spec["tmpl"], spec.get("unit")
    return None, None


def _leaf_tables(sem, fmt: str, prefix: str) -> list[str]:
    lines = [f"local {prefix} = {{"]
    for name, rule in sem.leaves.items():
        tmpl, _unit = _leaf_tmpl(rule, fmt)
        if tmpl is not None:
            lines.append(f"  {name} = {_lua_str(tmpl)},")
    lines.append("}")
    lines.append(f"local {prefix}_UNIT = {{")
    for name, rule in sem.leaves.items():
        _tmpl, unit = _leaf_tmpl(rule, fmt)
        if unit:
            lines.append(f"  {name} = {_lua_str(str(unit))},")
    lines.append("}")
    return lines


def _leaf_body(sem) -> list[str]:
    lines = _leaf_tables(sem, "latex", "LEAF_LATEX") + _leaf_tables(sem, "typst", "LEAF_TYPST")
    lines.append("local LEAF_HTML = {")
    for name, rule in sem.leaves.items():
        html = rule.get("html")
        if isinstance(html, dict) and html.get("tag") and html.get("class"):
            parts = [f"tag = {_lua_str(str(html['tag']))}", f"class = {_lua_str(str(html['class']))}"]
            if html.get("style"):
                parts.append(f"style = {_lua_str(str(html['style']))}")
            if html.get("unit"):
                parts.append(f"unit = {_lua_str(str(html['unit']))}")
            lines.append(f"  {name} = {{ {', '.join(parts)} }},")
    lines.append("}")
    return lines


def _divboxes_body(sem) -> list[str]:
    """class -> tcolorbox env for the box-family blocks (latex.box == true).

    Only these classes are owned by divboxes.lua; other env-based blocks
    (largefontblock / blockindent / center) are handled by their own filters,
    so restricting to latex.box avoids double-wrapping.
    """
    lines = ["local BLOCK_ENV = {"]
    for name, rule in sem.blocks.items():
        latex = rule.get("latex") or {}
        if latex.get("box") and latex.get("env"):
            lines.append(f"  {_lua_key(name)} = {_lua_str(str(latex['env']))},")
    lines.append("}")
    return lines


# filter filename -> body generator
_TARGETS = {
    "semantic-spans.lua": _spans_body,
    "semantic-leaf.lua": _leaf_body,
    "divboxes.lua": _divboxes_body,
}


def _detect_nl(text: str) -> str:
    return "\r\n" if "\r\n" in text else "\n"


def _process(path: Path, body_lines: list[str], check: bool) -> bool:
    """Return True if the file is (or would be) up to date; False if stale."""
    with open(path, "r", encoding="utf-8", newline="") as f:
        text = f.read()
    nl = _detect_nl(text)
    region = nl.join([_BEGIN, *body_lines, _END])
    new_text, n = _REGION_RE.subn(lambda _m: region, text)
    if n == 0:
        raise SystemExit(f"error: GENERATED マーカーが見つかりません: {path}")
    if new_text == text:
        return True
    if check:
        return False
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(new_text)
    return False  # was stale, now rewritten


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="生成せず、ドリフトがあれば終了コード 1")
    args = ap.parse_args()

    sem = load_semantics()
    stale: list[str] = []
    rewrote: list[str] = []
    for fname, body_fn in _TARGETS.items():
        path = _FILTERS_DIR / fname
        up_to_date = _process(path, body_fn(sem), args.check)
        if args.check:
            if not up_to_date:
                stale.append(fname)
        elif not up_to_date:
            rewrote.append(fname)

    if args.check:
        if stale:
            print("stale (semantics.yaml と不整合、再生成が必要): " + ", ".join(stale))
            return 1
        print("ok: Lua テーブルは semantics.yaml と一致")
        return 0

    if rewrote:
        print("regenerated: " + ", ".join(rewrote))
    else:
        print("no change: 既に最新")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
